// поэтому показываем его списком, а не числовым полем: варианты видны сразу,
// ошибочное значение руками не вбить. Единственный источник правды и для формы,
// и для её клиентской валидации.
export const DURATION_OPTIONS = [15, 30, 45, 60, 75, 90]
