// Формат email из спеки (`@format("email")` в spec/models.tsp) проверяет на
// сервере ajv-formats в режиме `fast` — режим задан явно в
// `apps/server/src/openapi.ts` (`ajvFormats: { mode: 'fast' }`). Ниже — тот же
// шаблон из набора форматов, скопированный дословно.
//
// Зеркало нужно ради UX: подсказка появляется мгновенно, без round-trip и без
// отправки формы. Асимметрия в одну сторону безопасна — клиент мягче сервера
// лишь отправит запрос и увидит русский канон §5, строже — заставит гостя
// исправлять поле до отправки. Правки сюда и в spec/models.tsp должны идти
// вместе.
const EMAIL_PATTERN =
  /^[a-z0-9.!#$%&'*+/=?^_`{|}~-]+@[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)*$/i

export function isValidEmail(value: string): boolean {
  return EMAIL_PATTERN.test(value)
}

